package fr.inria.corese.core.next.data.api.term;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.NullAndEmptySource;
import org.junit.jupiter.params.provider.ValueSource;

import fr.inria.corese.core.next.data.api.exception.IncorrectFormatException;

class SimpleIRITest extends IRITest {
    private static final String NAMESPACE = "http://example.org/";
    private static final String FULL_IRI = NAMESPACE + "term";

    @Override
    public IRI createIRI(String iri) {
        return new SimpleIRI(iri);
    }

    @Override
    public IRI createIRI(String namespace, String localName) {
        return new SimpleIRI(namespace, localName);
    }

    @Test
    void createsIRIFromFullString() {
        SimpleIRI iri = new SimpleIRI(FULL_IRI);

        assertEquals(NAMESPACE, iri.getNamespace());
        assertEquals("term", iri.getLocalName());
        assertEquals(FULL_IRI, iri.stringValue());
    }

    @Test
    void createsIRIFromNamespaceAndLocalName() {
        SimpleIRI iri = new SimpleIRI(NAMESPACE, "term");

        assertEquals(NAMESPACE, iri.getNamespace());
        assertEquals("term", iri.getLocalName());
        assertEquals(FULL_IRI, iri.stringValue());
    }

    @Test
    void equalityAndHashCodeDependOnFullIRI() {
        SimpleIRI full = new SimpleIRI(FULL_IRI);
        SimpleIRI split = new SimpleIRI(NAMESPACE, "term");

        assertEquals(full, split);
        assertEquals(split, full);
        assertEquals(full.hashCode(), split.hashCode());
        assertNotEquals(full, new SimpleIRI(NAMESPACE, "other"));
        assertNotEquals(null, full);
        assertNotEquals(FULL_IRI, full);
    }

    @Test
    void cachedHashPreservesCanonicalHashAndSurvivesSerialization() throws Exception {
        // The supplied split need not be the canonical split inferred from the full IRI.
        SimpleIRI iri = new SimpleIRI("http://example.org/", "path#term");
        var reference = new fr.inria.corese.core.next.data.spi.term.AbstractIRI(iri.stringValue()) { };
        assertEquals(reference.hashCode(), iri.hashCode());
        assertEquals(new SimpleIRI(iri.stringValue()).hashCode(), iri.hashCode());
        var bytes = new java.io.ByteArrayOutputStream();
        try (var output = new java.io.ObjectOutputStream(bytes)) { output.writeObject(iri); }
        try (var input = new java.io.ObjectInputStream(new java.io.ByteArrayInputStream(bytes.toByteArray()))) {
            SimpleIRI restored = (SimpleIRI) input.readObject();
            assertEquals(iri, restored);
            assertEquals(reference.hashCode(), restored.hashCode());
            assertEquals(iri.hashCode(), restored.hashCode());
        }
    }

    @Test
    void readsIriSerializedBeforeHashCacheWasIntroduced() throws Exception {
        // Generated by the original SimpleIRI class, with its unchanged serialVersionUID.
        byte[] bytes = java.util.Base64.getDecoder().decode(
                "rO0ABXNyADFmci5pbnJpYS5jb3Jlc2UuY29yZS5uZXh0LmRhdGEuYXBpLnRlcm0uU2ltcGxlSVJJ3hMxQG9xFt4C"
                + "AAB4cgAzZnIuaW5yaWEuY29yZXNlLmNvcmUubmV4dC5kYXRhLnNwaS50ZXJtLkFic3RyYWN0SVJJ8gsYbESJkyEC"
                + "AAJMAAlsb2NhbE5hbWV0ABJMamF2YS9sYW5nL1N0cmluZztMAAluYW1lc3BhY2VxAH4AAnhwdAAJcGF0aCN0ZXJt"
                + "dAATaHR0cDovL2V4YW1wbGUub3JnLw==");
        try (var input = new java.io.ObjectInputStream(new java.io.ByteArrayInputStream(bytes))) {
            SimpleIRI restored = (SimpleIRI) input.readObject();
            var reference = new fr.inria.corese.core.next.data.spi.term.AbstractIRI(restored.stringValue()) { };
            assertEquals("http://example.org/path#term", restored.stringValue());
            assertEquals(reference.hashCode(), restored.hashCode());
        }
    }

    @ParameterizedTest
    @NullAndEmptySource
    @ValueSource(strings = {" ", "relative/path", "http://example.org/invalid path"})
    void rejectsInvalidFullIRI(String iri) {
        assertThrows(IncorrectFormatException.class, () -> new SimpleIRI(iri));
    }

    @ParameterizedTest
    @ValueSource(strings = {"invalid name", "\t", "\n"})
    void rejectsInvalidNamespaceAndLocalNameCombination(String localName) {
        assertThrows(IncorrectFormatException.class, () -> new SimpleIRI(NAMESPACE, localName));
    }
}
